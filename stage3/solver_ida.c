/* ---- Author's search (exercises 4 and 5) ---- */

static uint8_t my_h(uint16_t p, uint16_t o)
{
    uint8_t h1 = my_pdb_p[p];
    uint8_t h2 = my_pdb_o[o];
    return (h1 > h2 ? h1 : h2);
}

/* Field order follows the Stage 4 frame layout (12 bytes, word-aligned):
 * 0 p, 2 o, 4 np, 6 no, 8 face, 9 turn, 10 last_face. In the exercise the
 * order was p, o, face, turn, np, no, last_face; only the order changed.
 */
typedef struct {
    uint16_t p, o; /* 這一層的節點 */
    uint16_t np, no; /* 這一層的下一個子節點的狀態 */
    uint8_t face, turn; /* 這一層的下一個子節點 */
    uint8_t last_face;
} frame_t;

/* 11 frames: a pushed node is unsolved (h >= 1) and unpruned (g + h <=
 * bound), so g <= bound - 1 <= 10. */
static frame_t stack[11];

static int my_search(uint16_t p, uint16_t o, uint8_t bound, uint8_t path[])
{
    frame_t *fr = stack;   /* 目前這一層，等於 &stack[g] */
    uint8_t g = 0;

    /* 根節點：呼叫前 my_solve 已確認不是已解，而且 h <= bound */
    fr->p = fr->np = p;
    fr->o = fr->no = o;
    fr->face = fr->turn = 0;
    fr->last_face = 3;
    COUNT_NODE();

    for (;;) {
        if ( fr->face == 3) {
            if (g == 0)
                return -1;              /* 這一輪 bound 失敗 */
            /* pop：回到上一層 */
            --g;
            fr = &stack[g];
            continue;
        }
        if (fr->turn == 3 || fr->face == fr->last_face) {
            /* 換下一個 face：face + 1，turn 歸零，np/no 重設 */
            ++fr->face;
            fr->turn = 0;
            fr->np = fr->p;
            fr->no = fr->o;
            continue;
        }

        /* 產生下一個子節點 */
        fr->np = my_perm_move[fr->face][fr->np];
        fr->no = my_ori_move[fr->face][fr->no];
        path[g] = (fr->face << 1U) + fr->face + fr->turn;
        ++fr->turn;
        if (fr->np == 0 && fr->no == 0)
            return g + 1;
        if (g + 1 + my_h(fr->np, fr->no) > bound)
            continue;
        /* push：設定下一層的 7 個欄位，fr 往下一層，g + 1 */
        ++g;
        fr = &stack[g];
        fr->face = 0;
        fr->turn = 0;
        fr->last_face = stack[g - 1].face;
        fr->p = fr->np = stack[g - 1].np;
        fr->o = fr->no = stack[g - 1].no;
        COUNT_NODE();
    }
}

static int my_solve(uint16_t p, uint16_t o, uint8_t path[])
{
    if (p == 0 && o == 0)
        return 0;

    uint8_t bound = my_h(p, o);

    while (bound <= 11) {
        int len = my_search(p, o, bound, path);
        if (len >= 0)
            return len;
        ++bound;
    }

    return -1;
}

/* ---- [glue] input validation and replay check ---- */

/* 7 cubie digits '1'..'7' (distinct), 7 twist digits '1'..'3' with the sum
 * of twists 0 mod 3, then the terminator. Fills p[] and o[] 0-based.
 */
static int parse_state(const char *s, uint8_t p[CUBIES], uint8_t o[CUBIES])
{
    uint8_t seen = 0, sum = 0;
    for (int i = 0; i < CUBIES; ++i) {
        uint8_t c = (uint8_t) (s[i] - '1');
        if (c >= CUBIES || (seen >> c) & 1U)
            return 0;
        seen |= (uint8_t) (1U << c);
        p[i] = c;
    }
    for (int i = 0; i < CUBIES; ++i) {
        uint8_t t = (uint8_t) (s[CUBIES + i] - '1');
        if (t >= 3)
            return 0;
        o[i] = t;
        sum = (uint8_t) (sum + t);
    }
    while (sum >= 3)
        sum = (uint8_t) (sum - 3U);
    return s[14] == '\0' && sum == 0;
}

/* T5: apply the returned path with the tables; it must reach (0, 0). A move
 * m = face * 3 + turn is turn + 1 quarter turns of face.
 */
static int replay_ok(uint16_t p, uint16_t o, const uint8_t path[], int len)
{
    for (int k = 0; k < len; ++k) {
        uint8_t face = 0, turns = path[k];
        while (turns >= 3) {
            turns = (uint8_t) (turns - 3U);
            ++face;
        }
        for (uint8_t t = 0; t <= turns; ++t) {
            p = my_perm_move[face][p];
            o = my_ori_move[face][o];
        }
    }
    return p == 0 && o == 0;
}

