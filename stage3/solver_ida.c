extern const uint16_t perm_move[3][PERMUTATIONS];
extern const uint16_t ori_move[3][ORIENTATIONS];
extern const uint8_t pdb_p[PERMUTATIONS], pdb_o[ORIENTATIONS];
#define my_perm_move perm_move
#define my_ori_move ori_move
#define my_pdb_p pdb_p
#define my_pdb_o pdb_o

/* Author's ranking functions (exercise 1), as in practice/my_tables.h. */
static const uint16_t weight[CUBIES] = {720, 120, 24, 6, 2, 1, 1};

static uint16_t my_rank_perm(const uint8_t p[CUBIES])
{
    uint16_t rank = 0;
    for (uint8_t i = 0; i < CUBIES; ++i){
        for (uint8_t j = (uint8_t) (i + 1U); j < CUBIES; ++j){
            if (p[j] < p[i]){
                rank += weight[i];
            }
        }
    }

    return rank;
}

static uint16_t my_rank_ori(const uint8_t o[CUBIES])
{
    uint16_t rank = 0;
    for (uint8_t i = 0; i < 6; ++i){
        rank = (rank << 1) + rank + o[i];
    }

    return rank;
}
