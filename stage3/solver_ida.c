#include <stdio.h>

int main(int argc, char **argv)
{
    uint8_t p[CUBIES], o[CUBIES], path[11];
    if (argc != 2 || !parse_state(argv[1], p, o)) {
        fprintf(stderr, "usage: %s PPPPPPPOOOOOOO\n",
                argc > 0 && argv[0] ? argv[0] : "solver_ida");
        return 2;
    }
    my_init_tables();
    uint16_t pr = my_rank_perm(p), orr = my_rank_ori(o);
    int len = my_solve(pr, orr, path);
    if (len < 0 || !replay_ok(pr, orr, path, len)) {
        fputs("FAIL\n", stderr);
        return 1;
    }
    for (int i = 0; i < len; ++i)
        printf("%s%s", i ? " " : "", move_names[path[i]]);
    putchar('\n');
#ifdef COUNT
    fprintf(stderr, "%llu expanded\n", (unsigned long long) expanded);
#endif
    return fflush(stdout) != 0 || ferror(stdout);
}
